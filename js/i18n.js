let lang = 'en';
try {
  const saved = localStorage.getItem('lang');
  if (saved === 'bn' || saved === 'en') lang = saved;
} catch { /* storage blocked */ }

export function getLang() { return lang; }

export function t(key, params) {
  const table = dict[lang] || dict.en;
  let s = Object.prototype.hasOwnProperty.call(table, key) ? table[key]
    : Object.prototype.hasOwnProperty.call(dict.en, key) ? dict.en[key] : key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, p) => (p in params ? (typeof params[p] === 'number' ? num(params[p]) : String(params[p])) : m));
  return s;
}

const BN_DIGITS = '০১২৩৪৫৬৭৮৯';
// Numbers we generate ourselves (counts, pages) are shown in Bangla digits in bn.
export function num(n) {
  const s = String(n);
  return lang === 'bn' ? s.replace(/[0-9]/g, (d) => BN_DIGITS[d]) : s;
}

export function applyStatic(root = document) {
  document.documentElement.lang = lang;
  document.title = t('app.title');
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.setAttribute('title', t(el.dataset.i18nTitle));
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
}

export function setLang(next) {
  if (next !== 'en' && next !== 'bn') return;
  lang = next;
  try { localStorage.setItem('lang', next); } catch { /* ignore */ }
  document.documentElement.lang = next;
  applyStatic();
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: next } }));
}
